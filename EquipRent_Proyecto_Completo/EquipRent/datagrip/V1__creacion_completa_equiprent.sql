-- 17. historial_estado_unidad
CREATE TABLE historial_estado_unidad (
    historial_id     BIGINT GENERATED BY DEFAULT AS IDENTITY,
    unidad_id        BIGINT       NOT NULL,
    estado_anterior  VARCHAR(20)  NULL,   -- NULL en el alta de la unidad
    estado_nuevo     VARCHAR(20)  NOT NULL,
    motivo           VARCHAR(200) NULL,
    cambiado_por     BIGINT       NULL,
    cambiado_at      TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT pk_historial_estado_unidad PRIMARY KEY (historial_id),
    CONSTRAINT fk_historial_unidad FOREIGN KEY (unidad_id) REFERENCES unidad_equipo (unidad_id),
    CONSTRAINT fk_historial_cambiado_por FOREIGN KEY (cambiado_por) REFERENCES usuario (usuario_id),
    CONSTRAINT ck_historial_estado_nuevo CHECK (estado_nuevo IN
        ('DISPONIBLE','ENTREGADA','EN_INSPECCION','MANTENIMIENTO','BLOQUEADA','BAJA')),
    CONSTRAINT ck_historial_estado_anterior CHECK (estado_anterior IS NULL OR estado_anterior IN
        ('DISPONIBLE','ENTREGADA','EN_INSPECCION','MANTENIMIENTO','BLOQUEADA','BAJA'))
);

-- 18. auditoria
CREATE TABLE auditoria (
    auditoria_id  BIGINT GENERATED BY DEFAULT AS IDENTITY,
    usuario_id    BIGINT      NULL,
    entidad       VARCHAR(60) NOT NULL,
    entidad_id    BIGINT      NULL,
    accion        VARCHAR(40) NOT NULL,
    es_excepcion  BOOLEAN     NOT NULL DEFAULT FALSE,
    detalle       JSONB       NULL,
    created_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT pk_auditoria PRIMARY KEY (auditoria_id),
    CONSTRAINT fk_auditoria_usuario FOREIGN KEY (usuario_id) REFERENCES usuario (usuario_id)
);

-- ---------------------------------------------------------------------
-- RN-10 · El historial del activo no se elimina
-- ---------------------------------------------------------------------
CREATE OR REPLACE FUNCTION fn_impedir_borrado_historico()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    RAISE EXCEPTION 'RN-10: los registros de % no se pueden eliminar', TG_TABLE_NAME;
END;
$$;

CREATE TRIGGER trg_historial_no_delete
    BEFORE DELETE ON historial_estado_unidad
    FOR EACH ROW EXECUTE FUNCTION fn_impedir_borrado_historico();

CREATE TRIGGER trg_auditoria_no_delete
    BEFORE DELETE ON auditoria
    FOR EACH ROW EXECUTE FUNCTION fn_impedir_borrado_historico();

